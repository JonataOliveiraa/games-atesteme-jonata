export const cycleMs = (def: ThingDef) => def.cycle.reduce((sum, b) => sum + b.ms, 0)

export function beatIndexAt(def: ThingDef, t: number): number {
    let rest = ((t % cycleMs(def)) + cycleMs(def)) % cycleMs(def)
    for (let i = 0; i < def.cycle.length; i++) {
        if (rest < def.cycle[i].ms) return i
        rest -= def.cycle[i].ms
    }
    return def.cycle.length - 1
}

export const beatAt = (def: ThingDef, t: number): Beat => def.cycle[beatIndexAt(def, t)]

export const isActive = (beat: Beat) => beat.see || beat.hear

/** o formato guarda a coisa naquele instante? */
export const canKeep = (beat: Beat, tool: Tool) => (tool === 'photo' ? beat.see : beat.hear)

export const onlySee = (def: ThingDef) => def.cycle.some(b => b.see) && !def.cycle.some(b => b.hear)
/** algum instante em que a coisa só se vê (a foto vale, o som não) */
export const hasSeeOnly = (def: ThingDef) => def.cycle.some(b => b.see && !b.hear)
/** algum instante em que a coisa só se ouve (o som vale, a foto não) */
export const hasHearOnly = (def: ThingDef) => def.cycle.some(b => b.hear && !b.see)
export const onlyHear = (def: ThingDef) => def.cycle.some(b => b.hear) && !def.cycle.some(b => b.see)

export const contains = (def: ThingDef, x: number, y: number) =>
    Math.abs(x - def.x) <= def.w / 2 && Math.abs(y - def.y) <= def.h / 2
